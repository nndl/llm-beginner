"""Search filenames and text under the task workspace only."""
from pathlib import Path
# ============================================================
# 工具 Schema
# ============================================================
TOOL_SCHEMA = {
    "type": "function",     # 表示这是一个 Function Tool。
    "function": {
        "name": "file_search",  # 工具名称。后面的 Agent 可以通过这个名字知道应该调用 file_search。
        "description": "Find filenames or content matching a literal pattern within a local directory.",  # 工具描述：在本地目录中搜索：1. 文件名匹配的文件；2. 文件内容包含指定字符串的文件
        "parameters": {
            "type": "object",
            "properties": {
                "pattern": {"type": "string", "description": "Filename glob or literal content"},# 要搜索的内容。
                "dir": {"type": "string", "description": "Directory inside this task workspace"},# 要搜索的目录。
            },
            "required": ["pattern", "dir"],# pattern 和 dir 都是必填参数。
            "additionalProperties": False,# 不允许传入其他未定义的参数。
        },
    },
}
# ============================================================
# 确定任务工作区根目录
# ============================================================
_ROOT = Path(__file__).resolve().parents[2]

# ============================================================
# 工具真正的执行入口
# ============================================================
def run(args: dict) -> str:
    """
    执行文件搜索。

    args 示例：

    {
        "pattern": "calculator",
        "dir": "/project/tools"
    }

    返回：
        匹配到的文件路径以及文件内容片段。
    """


    # --------------------------------------------------------
    # 1. 获取参数
    # --------------------------------------------------------

    pattern, directory = args.get("pattern"), args.get("dir")
    # --------------------------------------------------------
    # 2. 检查 pattern
    # --------------------------------------------------------
    if not isinstance(pattern, str) or not pattern:
        # pattern 必须是字符串，
        # 并且不能为空。
        raise ValueError("'pattern' must be a non-empty string")
    # --------------------------------------------------------
    # 3. 检查 dir
    # --------------------------------------------------------
    if not isinstance(directory, str):
        # directory 必须是字符串。
        raise ValueError("'dir' must be a string")
    # --------------------------------------------------------
    # 4. 将用户提供的目录转换成绝对路径
    # --------------------------------------------------------
    target = Path(directory).resolve()
    # --------------------------------------------------------
    # 5. 安全检查：目录必须位于任务工作区内部
    # --------------------------------------------------------
    if target != _ROOT and _ROOT not in target.parents:
        raise ValueError("Directory must be inside the task workspace")
    # --------------------------------------------------------
    # 6. 检查目录是否真实存在
    # --------------------------------------------------------
    if not target.is_dir():
        raise ValueError(f"Not a directory: {directory}")
    # --------------------------------------------------------
    # 7. 保存搜索结果
    # --------------------------------------------------------
    matches = []
    # --------------------------------------------------------
    # 8. 递归遍历目录下的所有文件
    # --------------------------------------------------------
    for path in sorted(target.rglob("*")):
        # rglob("*")：
        # 递归搜索 target 下面的所有文件和目录。
        #
        # 例如：
        #
        # /project
        # ├── tools
        # │   ├── calculator.py
        # │   └── file_search.py
        # ├── data
        # │   └── test.txt
        # └── README.md
        #
        # rglob("*") 会递归遍历这些内容。
        #
        # sorted()：
        # 按路径排序，让输出结果更加稳定。


        # ----------------------------------------------------
        # 9. 过滤掉目录和过大的文件
        # ----------------------------------------------------
        if not path.is_file() or path.stat().st_size > 200_000:
            continue
        # ----------------------------------------------------
        # 10. 计算相对于工作区根目录的路径
        # ----------------------------------------------------
        relative = path.relative_to(_ROOT)
        # ----------------------------------------------------
        # 11. 读取文件内容
        # ----------------------------------------------------
        text = path.read_text(encoding="utf-8", errors="replace")
        # ----------------------------------------------------
        # 12. 判断文件名是否匹配
        # ----------------------------------------------------
        filename_match = path.match(pattern) or pattern.lower() in path.name.lower()
        # ----------------------------------------------------
        # 13. 判断文件内容是否匹配
        # ----------------------------------------------------
        content_match = pattern.lower() in text.lower()
        # ----------------------------------------------------
        # 14. 文件名或者文件内容匹配
        # ----------------------------------------------------
        if filename_match or content_match:
            # ------------------------------------------------
            # 15. 截取文件前 500 个字符
            # ------------------------------------------------

            snippet = text[:500].replace("\x00", " ").strip()
            # ------------------------------------------------
            # 16. 保存搜索结果
            # ------------------------------------------------
            matches.append(f"{relative}\n{snippet}")
    # ========================================================
    # 17. 返回最终搜索结果
    # ========================================================
    return "\n\n".join(matches) if matches else "No matches found."