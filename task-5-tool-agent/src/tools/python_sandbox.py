"""Teaching-only Python sandbox; never use it for untrusted code."""
import ast
import builtins
import contextlib
import io
import multiprocessing as mp
# ============================================================
# Tool Schema
# ============================================================
TOOL_SCHEMA = {
    "type": "function",
    "function": {
        "name": "python_sandbox",
        "description": "Run a short Python calculation and return its printed output.",
        # 工具描述。
        #
        # 告诉 Agent：
        # 这个工具用于运行较短的 Python 计算，
        # 最终返回 print() 输出的内容。
        "parameters": {
            "type": "object",
            "properties": {"code": {"type": "string", "description": "Python code to execute"}},# 需要执行的 Python 代码。
            "required": ["code"],
            "additionalProperties": False,
        },
    },
}
# ============================================================
# 允许使用的 Python 内置函数
# ============================================================
_BUILTINS = {name: getattr(builtins, name) for name in (
    "abs", "all", "any", "bool", "dict", "enumerate", "filter", "float", "int", "len",
    "list", "map", "max", "min", "print", "range", "reversed", "round", "set", "sorted",
    "str", "sum", "tuple", "zip")}

# ============================================================
# 检查代码是否包含明显的危险语法
# ============================================================
def _reject_unsafe(code: str) -> None:
    """
    在执行 Python 代码之前进行 AST 安全检查。

    这个函数并不是保证代码绝对安全，
    而是过滤掉一些明显不允许的语法。
    """

    # --------------------------------------------------------
    # 1. 将代码解析成 AST
    # --------------------------------------------------------
    tree = ast.parse(code, mode="exec")
     # --------------------------------------------------------
    # 2. 遍历 AST 中的所有节点
    # --------------------------------------------------------
    for node in ast.walk(tree):
        # ----------------------------------------------------
        # 3. 禁止 import
        # ----------------------------------------------------
        if isinstance(node, (ast.Import, ast.ImportFrom, ast.With, ast.AsyncWith, ast.Global, ast.Nonlocal)):
            raise ValueError("Imports and scope-changing statements are not allowed")
        # ----------------------------------------------------
        # 4. 禁止访问 dunder 属性
        # ----------------------------------------------------
        if isinstance(node, ast.Attribute) and node.attr.startswith("__"):
            raise ValueError("Dunder attribute access is not allowed")
        # ----------------------------------------------------
        # 5. 禁止 dunder 名称
        # ----------------------------------------------------
        if isinstance(node, ast.Name) and node.id.startswith("__"):
            raise ValueError("Dunder names are not allowed")

# ============================================================
# 真正执行 Python 代码的子进程函数
# ============================================================
def _worker(code: str, queue) -> None:
    """
    在独立子进程中执行用户代码。
    """

    # --------------------------------------------------------
    # 1. 创建输出缓冲区
    # --------------------------------------------------------
    output = io.StringIO()
    try:
        # ----------------------------------------------------
        # 2. 捕获 print() 输出
        # ----------------------------------------------------
        with contextlib.redirect_stdout(output):
            exec(compile(code, "<sandbox>", "exec"), {"__builtins__": _BUILTINS}, {})
        # ----------------------------------------------------
        # 3. 把执行成功的结果放入队列
        # ----------------------------------------------------
        queue.put((True, output.getvalue()))
    except Exception as error:
        # ----------------------------------------------------
        # 4. 如果执行过程中发生异常
        # ----------------------------------------------------
        queue.put((False, f"{type(error).__name__}: {error}"))

# ============================================================
# 对外统一入口
# ============================================================
def run(args: dict) -> str:
    """
    python_sandbox 工具的统一入口。

    args 示例：

    {
        "code": "print(sum(range(10)))"
    }

    返回：
        Python 代码产生的标准输出。
    """

    # --------------------------------------------------------
    # 1. 获取 code
    # --------------------------------------------------------
    code = args.get("code")
    # --------------------------------------------------------
    # 2. 检查 code 是否有效
    # --------------------------------------------------------
    if not isinstance(code, str) or not code.strip():
        # code 必须：
        # 1. 是字符串；
        # 2. 不能为空；
        # 3. 不能只有空格。
        raise ValueError("'code' must be a non-empty string")
    # --------------------------------------------------------
    # 3. 限制代码长度
    # --------------------------------------------------------
    if len(code) > 4_000:
        raise ValueError("Code is too long")
    # --------------------------------------------------------
    # 4. 执行 AST 安全检查
    # --------------------------------------------------------
    _reject_unsafe(code)
    # --------------------------------------------------------
    # 5. 创建进程间通信队列
    # --------------------------------------------------------
    queue = mp.Queue()
    # --------------------------------------------------------
    # 6. 创建子进程
    # --------------------------------------------------------
    process = mp.Process(target=_worker, args=(code, queue))
    # --------------------------------------------------------
    # 7. 启动子进程
    # --------------------------------------------------------
    process.start()
    # --------------------------------------------------------
    # 8. 最多等待 2 秒
    # --------------------------------------------------------
    process.join(2)
    # --------------------------------------------------------
    # 9. 检查是否超时
    # --------------------------------------------------------
    if process.is_alive():
        process.terminate()
        process.join()
        raise TimeoutError("Sandbox timed out after 2 seconds")
    # --------------------------------------------------------
    # 10. 检查子进程有没有返回结果
    # --------------------------------------------------------
    if queue.empty():
        raise RuntimeError("Sandbox exited without a result")
    # --------------------------------------------------------
    # 11. 获取执行结果
    # --------------------------------------------------------
    ok, result = queue.get()
    # --------------------------------------------------------
    # 12. 检查 Python 代码是否执行成功
    # --------------------------------------------------------
    if not ok:
        raise RuntimeError(result)
    # --------------------------------------------------------
    # 13. 返回程序输出
    # --------------------------------------------------------
    return result.rstrip() or "(no output)"